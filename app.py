def esc(v):
    return html.escape(str(v), quote=True)


def compact(s):
    """يضغط الـ HTML في سطر واحد (يمنع Markdown من تفسير المسافات كأكواد)."""
    return " ".join(s.split())


def ul(items):
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def card(title, body, tone=""):
    return f'<div class="fc-card {tone}"><h4>{title}</h4>{body}</div>'


def details(title, body, open_all=False):
    o = " open" if open_all else ""
    return f'<details class="fc-det"{o}><summary>{title}</summary><div>{body}</div></details>'


def table_html(headers, rows, hl=None):
    head = "".join(f"<th>{h}</th>" for h in headers)
    body = ""
    for i, row in enumerate(rows):
        c = ' class="hl"' if hl is not None and i in hl else ""
        body += f"<tr{c}>" + "".join(f"<td>{cell}</td>" for cell in row) + "</tr>"
    return (
        '<div class="fc-scroll"><table class="fc-table"><thead><tr>'
        f"{head}</tr></thead><tbody>{body}</tbody></table></div>"
    )


