def calc_age(dob, today):
    years = today.year - dob.year
    months = today.month - dob.month
    days = today.day - dob.day
    if days < 0:
        months -= 1
        days += (today.replace(day=1) - datetime.timedelta(days=1)).day
    if months < 0:
        years -= 1
        months += 12
    total_days = (today - dob).days
    return dict(years=years, months=months, days=days, total_days=total_days,
                weeks=total_days // 7, total_months=years * 12 + months)


