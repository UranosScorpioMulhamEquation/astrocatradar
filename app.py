def fallback_sun_sign(d):
    idx = 9  # الجدي قبل 20 يناير
    for m, day, i in _CUTOFFS:
        if (d.month, d.day) >= (m, day):
            idx = i
    return idx


def calc_body(jd, body_id):
    for flags in (swe.FLG_SWIEPH | swe.FLG_SPEED, swe.FLG_MOSEPH | swe.FLG_SPEED):
        try:
            pos, _ = swe.calc_ut(jd, body_id, flags)
            return pos
        except Exception:
            continue
    return None


def compute_chart(dob):
    """الحساب على الساعة 12:00 UTC (ساعة الميلاد غير معروفة)، أبراج استوائية."""
    jd = swe.julday(dob.year, dob.month, dob.day, 12.0)
    chart, sun_idx = [], None
    for ar, en, pid, is_ast in BODIES:
        pos = calc_body(jd, pid)
        row = {"ar": ar, "en": en, "ast": is_ast, "ok": pos is not None}
        if pos is not None:
            lon = pos[0] % 360
            row.update(lon=lon, sign_idx=int(lon // 30), deg=lon % 30, retro=pos[3] < 0)
            if ar == "الشمس":
                sun_idx = row["sign_idx"]
        chart.append(row)
    if sun_idx is None:
        sun_idx = fallback_sun_sign(dob)
    for row in chart:
        if row["ok"]:
            row["house"] = (row["sign_idx"] - sun_idx) % 12 + 1  # كل برج بيت من برج الشمس
    return chart, sun_idx


def sun_aspects(chart):
    sun = chart[0]
    out = []
    if not sun["ok"]:
        return out
    for b in chart[1:]:
        if not b["ok"]:
            continue
        diff = abs(sun["lon"] - b["lon"]) % 360
        if diff > 180:
            diff = 360 - diff
        for name, angle, orb in ASPECTS:
            if abs(diff - angle) <= orb:
                out.append({"body": b, "aspect": name, "orb": abs(diff - angle)})
                break
    return out


