def sign_of(chart, name):
    for b in chart:
        if b["ar"] == name and b["ok"]:
            return ZODIAC[b["sign_idx"]]
    return None


def element_balance(chart):
    el, mo = [0] * 4, [0] * 3
    for b in chart:
        if b["ok"]:
            el[b["sign_idx"] % 4] += 1
            mo[b["sign_idx"] % 3] += 1
    return el, mo


def body_aspects(chart, include_sun=False):
    """اتصالات الكواكب والكويكبات فيما بينها (بفوارق أضيق من اتصالات الشمس)."""
    ok = [b for b in chart if b["ok"] and (include_sun or b["ar"] != "الشمس")]
    out = []
    for i in range(len(ok)):
        for j in range(i + 1, len(ok)):
            b1, b2 = ok[i], ok[j]
            diff = abs(b1["lon"] - b2["lon"]) % 360
            if diff > 180:
                diff = 360 - diff
            for name, angle, _ in ASPECTS:
                if abs(diff - angle) <= TIGHT_ORBS[angle]:
                    out.append({"b1": b1, "b2": b2, "aspect": name, "orb": abs(diff - angle)})
                    break
    return out


def med_attention(r):
    """درجة الانتباه الطبي الفلكي لكل جرم (منهج ترفيهي مبسّط وشفاف)."""
    chart, aspects = r["chart"], r["aspects"]
    asp_by = {a["body"]["ar"]: a for a in aspects}
    rows = []
    for b in chart:
        if not b["ok"] or b["ar"] == "الشمس":
            continue
        score, why = 0, []
        if b["ar"] in CHALLENGING:
            score += 1
            why.append("جرم ثقيل/متحدٍّ في التقاليد")
        a = asp_by.get(b["ar"])
        if a:
            nm = a["aspect"]
            if nm in ("التربيع", "المقابلة"):
                score += 2
                why.append(f"{nm} مع الشمس (إجهاد للحيوية)")
            elif nm == "الاقتران" and b["ar"] in CHALLENGING:
                score += 2
                why.append("اقتران بالشمس مع جرم متحدٍّ")
            elif nm == "الاقتران":
                score += 1
                why.append("اقتران بالشمس")
            else:
                score -= 1
                why.append(f"{nm} مع الشمس (دعم)")
        if b["house"] in HEALTH_HOUSES:
            score += 1
            why.append(f'في البيت {ORD[b["house"] - 1]} (من بيوت الصحة)')
        level = "عالٍ" if score >= 3 else ("متوسط" if score == 2 else "منخفض")
        rows.append(dict(body=b, score=score, level=level, why=why))
    rows.sort(key=lambda x: -x["score"])
    return rows


