_GROWTH = [(0, 0.08), (2, 0.22), (4, 0.45), (6, 0.65), (9, 0.85), (12, 0.95), (18, 1.0)]


def estimate_weight(months, adult_kg):
    if months >= 18:
        return adult_kg
    for (m1, f1), (m2, f2) in zip(_GROWTH, _GROWTH[1:]):
        if m1 <= months <= m2:
            f = f1 + (f2 - f1) * (months - m1) / (m2 - m1)
            return max(0.3, round(adult_kg * f, 1))
    return adult_kg


DRY_KCAL_G = 3.8    # تقديري: 350–400 كيلوكالوري/100غ
