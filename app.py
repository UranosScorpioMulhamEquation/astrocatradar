def nutrition_plan(cat, age, stage, breed):
    if age["weeks"] < 8:
        return None
    months = age["total_days"] / 30.44
    est = cat["weight"] is None
    weight = estimate_weight(months, breed["kg"]) if est else cat["weight"]
    rer = weight * 30 + 70  # المعادلة المطلوبة في المشروع
    if stage == "kitten":
        factor = 2.5 if months < 4 else 2.0
    else:
        base = ({"خامل": 1.0, "متوسط": 1.2, "نشط": 1.4} if cat["neutered"]
                else {"خامل": 1.2, "متوسط": 1.4, "نشط": 1.6})
        factor = base[cat["activity"]]
        if cat["body"] == "زائدة الوزن":
            factor *= 0.8
        elif cat["body"] == "نحيفة":
            factor *= 1.1
    mer = round(rer * factor / 5) * 5
    if stage == "kitten":
        meals = "4 وجبات" if months < 6 else "3 وجبات"
    elif stage == "adult":
        meals = "2–3 وجبات"
    else:
        meals = "3 وجبات صغيرة"
    return dict(
        weight=weight, est=est, rer=rer, factor=factor, mer=mer, meals=meals,
        water_lo=weight * 40, water_hi=weight * 60,
        dry=mer / DRY_KCAL_G, wet=mer / WET_KCAL_G,
        mix_dry=mer * 0.5 / DRY_KCAL_G, mix_wet=mer * 0.5 / WET_KCAL_G)


